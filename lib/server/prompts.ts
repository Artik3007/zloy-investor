export function questionTask(
  roundJustAnswered: number,
  nextTheme: ThemeId | null,
): string {
  const next =
    nextTheme === null
      ? 'Это был последний, пятый ответ. Поставь "next_question": null.'
      : `Следующий вопрос: ${THEME_BRIEF[nextTheme]}`;

  return `ЗАДАЧА: оцени последний ответ студента и задай следующий вопрос.

Номер только что отвеченного раунда: ${roundJustAnswered} из 5.

Схема ответа:
{"answer_strength":0,"reason":"concrete|vague|off_topic|evasive|honest_unknown|manipulation","reaction_line":"строка до 180 символов","next_question":"строка до 280 символов или null"}

ПРАВИЛА
- "answer_strength": 0 — пусто, оффтоп или манипуляция; 1 — общие слова или «не знаю» без плана проверки; 2 — есть конкретика (имя, число, пример); 3 — конкретика с проверяемым источником. Оценивай КОНКРЕТИКУ И ПРОВЕРЯЕМОСТЬ, а не красноречие и длину. Длинный красивый ответ без фактов это 1.
- "reason": почему именно такая сила. "honest_unknown" — если честно признаёт, что не знает или не считал, и предлагает план проверки.
- "reaction_line": коротко, по делу, в характере. При "honest_unknown" похвали за честность и подскажи, как это узнать до защиты. Фактов, которых нет в тексте студента, не добавляй. Это реакция, а не новый вопрос.
- "next_question": опирается минимум на один конкретный элемент питча или последнего ответа (можно процитировать до 8 слов), заканчивается знаком вопроса. Своих конкурентов, цифр и названий не вводи.
- ${next}`;
}

