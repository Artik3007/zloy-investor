export function wrapPitch(pitch: string): string {
  return `<pitch>\n${escapeForPrompt(pitch)}\n</pitch>`;
}

export function wrapAnswers(answers: readonly string[]): string {
  return answers
    .map((a, i) => `<answer n="${i + 1}">\n${escapeForPrompt(a)}\n</answer>`)
    .join('\n');
}

