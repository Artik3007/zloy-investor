export function adviceTask(weakest: readonly { id: number; name: string }[]): string {
  const list = weakest.map((c) => `${c.id}. ${c.name}`).join('\n');
  return `ЗАДАЧА: дай ровно 3 совета, которые студент выполнит до выхода на сцену.

Три самых слабых критерия (посчитаны кодом, по одному совету на каждый, в этом порядке):
${list}

Схема ответа:
{"advice":[{"action":"","why":"","deadline_days":1,"done_when":""}]}

ПРАВИЛА
- Ровно 3 совета, по одному на каждый критерий из списка выше, в том же порядке.
- "action": начинается с глагола в повелительном наклонении и содержит объект или количество. Хорошо: «Напиши 10 потенциальным клиентам в ВК и спроси, как они решают проблему сегодня», «Посчитай на бумаге, сколько стоит привлечь одного клиента».
- ЗАПРЕЩЕНЫ общие формулировки: «проведи исследование рынка», «улучши презентацию», «подумай над моделью», «изучи рынок», «проработай стратегию». Совет выполним за дни, а не за месяцы.
- "why": одно предложение, зачем это инвестору.
- "deadline_days": целое число от 1 до 3.
- "done_when": как со стороны понять, что сделано (наблюдаемый признак).
- Опирайся только на то, что есть в питче и ответах. Новых фактов и цифр не вводи.`;
}
