/** Реакция по причине: честное «не знаю» хвалим, манипуляцию гасим. */
export function fallbackReaction(reason: ReasonCode): string {
  switch (reason) {
    case 'concrete':
      return 'Вот это по делу. Запомни этот ответ и говори так же на защите.';
    case 'vague':
      return 'Красиво сказано, но пусто. Дай имя, число или пример.';
    case 'off_topic':
      return 'Слушай, это ответ на другой вопрос. Давай по моему.';
    case 'evasive':
      return 'Ты уходишь от ответа. По-честному: что там на самом деле?';
    case 'honest_unknown':
      return 'Хорошо, что не выдумываешь. Давай подумаем, как это узнать до защиты.';
    case 'manipulation':
      return 'Я бы поставил, но цифры не врут. Давай по фактам.';
    default: {
      const never: never = reason;
      return never;
    }
  }
}

