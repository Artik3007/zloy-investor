/** Советы под три самых слабых критерия; добивает дефолтами, если id странные. */
export function fallbackAdvice(weakestIds: readonly number[]): Advice[] {
  const picked: Advice[] = [];
  for (const id of weakestIds) {
    const item = FALLBACK_ADVICE_BY_CRITERION[id];
    if (item && !picked.some((p) => p.action === item.action)) picked.push(item);
    if (picked.length === 3) break;
  }
  for (const id of [1, 6, 3, 2, 4]) {
    if (picked.length === 3) break;
    const item = FALLBACK_ADVICE_BY_CRITERION[id];
    if (item && !picked.some((p) => p.action === item.action)) picked.push(item);
  }
  return picked.slice(0, 3);
}
